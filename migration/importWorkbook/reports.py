"""Report and sanitized-fixture writers for the dry run.

The markdown report contains counts and identifiers only. The sanitized fixture
contains visible catalogue data with tenant hosts replaced; it has no hidden
rows, no protected notes and no credential.
"""
import json
from urllib.parse import urlsplit, urlunsplit

PLACEHOLDER_HOST = "tenant.example"


def _sanitize_link(link):
    if not link:
        return None
    clean = dict(link)
    for key in ("raw", "resolved"):
        value = clean.get(key)
        if value and value.startswith("http"):
            parts = urlsplit(value)
            clean[key] = urlunsplit((parts.scheme, PLACEHOLDER_HOST, parts.path, "", ""))
    return clean


def sanitized_fixture(model):
    """Visible catalogue and statistics only, with tenant hosts replaced and no protected text."""
    catalogue = {}
    for category, records in model["catalogue"].items():
        out = []
        for record in records:
            item = dict(record)
            item["titleLink"] = _sanitize_link(record.get("titleLink"))
            item["currentDirLink"] = _sanitize_link(record.get("currentDirLink"))
            item["sourceRef"] = _sanitize_link(record.get("sourceRef"))
            item["publishedRef"] = _sanitize_link(record.get("publishedRef"))
            item.pop("legacyPuneetRetained", None)
            # Person names are replaced in the preview; identities are resolved only by authorised lookup.
            if item.get("lastUpdatedBy"):
                item["lastUpdatedBy"] = "[editor]"
            if item.get("reviewer"):
                item["reviewer"] = "[reviewer]"
            out.append(item)
        catalogue[category] = out
    return {
        "_notice": "Sanitized local preview fixture. Visible catalogue data only. Not production data.",
        "homeContent": {
            "purpose": model["homeContent"]["purpose"],
            "showcaseLink": _sanitize_link(model["homeContent"]["showcaseLink"]),
        },
        "catalogue": catalogue,
        "statistics": {k: v for k, v in model["statistics"].items() if k != "headerDate"},
        "clients": model["clientRecords"],
    }


def write_fixture(model, path):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(sanitized_fixture(model), handle, indent=2, ensure_ascii=False, default=str)


def write_json_model(model, path):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(model, handle, indent=2, ensure_ascii=False, default=str)


def markdown_report(model):
    wb = model["workbook"]
    lines = [
        "# Migration dry-run report",
        "",
        "Generated by `python -m migration.importWorkbook`. Dry run only: no SharePoint writes.",
        "",
        "## Source",
        "",
        f"- File: `{wb['fileName']}`",
        f"- SHA-256 before read: `{wb['sha256Before']}`",
        f"- SHA-256 after read: `{wb['sha256After']}`",
        f"- Source unchanged: **{wb['sourceUnchanged']}**",
        "",
        "| Sheet | State | Max row |",
        "| --- | --- | --- |",
    ]
    for name, info in wb["sheets"].items():
        lines.append(f"| {name} | {info['state']} | {info['maxRow']} |")

    lines += ["", "## Exclusions", ""]
    for ex in model["exclusions"]:
        lines.append(f"- `{ex['sheet']}!{ex['cell']}`: {ex['reason']} (value not read into output)")

    lines += ["", "## Catalogue reconciliation", "",
              "| Category | Source rows | Records | Status counts (normalised) |",
              "| --- | --- | --- | --- |"]
    for category, rep in model["categories"].items():
        counts = ", ".join(f"{k}: {v}" for k, v in sorted(rep["statusCounts"].items())) or "none"
        lines.append(f"| {category} | {rep['sourceRows']} | {rep['records']} | {counts} |")
    lines += ["", f"**Total visible records: {model['totalVisibleRecords']}** (hidden rows are not catalogue records)", "",
              "## Home formula cross-check", "",
              "| Category | Home formula (cached) | Imported records |", "| --- | --- | --- |"]
    for category, check in model["homeCrossCheck"].items():
        cached = check["homeFormulaCached"] if check["homeFormulaCached"] is not None else "no formula"
        lines.append(f"| {category} | {cached} | {check['importedRecords']} |")

    lines += ["", "## Links", "", "| Sheet and link kind | Count |", "| --- | --- |"]
    for key, count in model["linkCounts"].items():
        lines.append(f"| {key} | {count} |")

    stats = model["statistics"]
    lines += ["", "## Company statistics", "",
              f"- FTE total recalculated from eligible components (rows 3-10): **{stats['fteTotal']}**",
              f"- Matches cached formula value: **{stats['fteTotalMatchesCachedFormula']}**",
              f"- Header date: {stats['headerDate']}", "",
              "| Row | Component | FTE | Share of total | Approval |", "| --- | --- | --- | --- | --- |"]
    for comp in stats["fteComponents"]:
        share = f"{comp['percentOfTotal']:.1%}" if comp["percentOfTotal"] is not None else "n/a"
        lines.append(f"| {comp['row']} | {comp['label']} | {comp['fte']} | {share} | {comp['approval']} |")
    lines += ["", "Outside the total (not summed):", ""]
    for out in stats["outsideTotal"]:
        lines.append(f"- Row {out['row']}: {out['label']} = {out['fte']} (approval: {out['approval']})")
    lines += ["", "Qualified statistics (kept as stated, not converted to exact numbers):", "",
              "| Row | Label | Raw | Number | Qualifier | Effective date | Approval |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for q in stats["qualifiedStatistics"]:
        v = q["value"]
        lines.append(f"| {q['row']} | {q['label']} | {v['raw']} | {v['number']} | {v['qualifier'] or 'exact'} | {q['effectiveDate'] or 'not recorded'} | {q['approval']} |")
    if stats["flags"]:
        lines += ["", "Flags: " + ", ".join(f"`{f}`" for f in stats["flags"])]

    clients = model["clients"]
    lines += ["", "## Client names", "",
              f"- Counts by domain: K12 {clients['countsByDomain']['K12']}, HE {clients['countsByDomain']['HE']}, WD {clients['countsByDomain']['WD']}",
              f"- Total entries: **{clients['totalEntries']}**; distinct clients: {clients['distinctClients']}",
              f"- Multi-domain clients (counted once in distinct total): {len(clients['multiDomainClients'])}",
              "- Logo-file availability: not verified (no logo library in dry run)."]

    hidden = model["hiddenEvidence"]
    lines += ["", "## Hidden legacy evidence (restricted; counts only)", "",
              "| Hidden sheet | Outcome | Rows |", "| --- | --- | --- |"]
    for sheet, outcomes in hidden["results"].items():
        for outcome, count in sorted(outcomes.items()):
            lines.append(f"| {sheet} | {outcome} | {count} |")
    lines += ["", "Protected note counts (text not reproduced): " + ", ".join(f"{k}={v}" for k, v in sorted(hidden["protectedNoteCounts"].items())),
              f"- Conflicting 550 claims located: {len(hidden['conflicts550'])} (cells: {', '.join(c['sheet'] + '!' + c['cell'] for c in hidden['conflicts550'])})",
              "- No hidden row becomes a catalogue record.", ""]

    lines += ["## Flag counts (catalogue)", ""]
    for flag, count in sorted(model["flagCounts"].items()):
        lines.append(f"- `{flag}`: {count}")
    lines.append("")
    return "\n".join(lines)


def write_markdown(model, path):
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(markdown_report(model))
